"""Copies a roster monster's body plan into the game as src/shared/Rigs/<Name>.luau.

    python tools/roster/rig_to_luau.py Puffgourd

Only the part between the BODY markers is rewritten, so the hand-made animations, walk cycle
and break settings further down the file survive when the design changes. The first run writes
the whole file with placeholders to fill in. Run `stylua src` afterwards.
"""

import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BEGIN = "-- BEGIN BODY (generated by tools/roster/rig_to_luau.py from tools/roster/rigs; do not edit)"
END = "-- END BODY"
SEGMENT_KEYS = ("name", "attach", "joint", "jointAt", "shape", "size", "pos", "rot", "color", "hitzone", "breaksWith", "tris")
DETAIL_KEYS = ("segment", "shape", "size", "pos", "rot", "color")


def lua(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        r = round(float(value), 3)
        return str(int(r)) if r == int(r) else repr(r)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(lua(v) for v in value) + " }"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{k} = {lua(v)}" for k, v in value.items()) + " }"
    raise TypeError(value)


def record(item, keys):
    return {k: item[k] for k in keys if item.get(k) is not None}


def body(rig):
    # One line per piece; StyLua is told to leave the block alone so it stays readable.
    lines = [BEGIN, "-- stylua: ignore start", "local body = {"]
    lines.append(f"\tdisplayName = {lua(rig['displayName'])},")
    lines.append(f"\thipHeight = {lua(rig['hipHeight'])},")
    lines.append(f"\trootSize = {lua(rig['rootSize'])},")
    lines.append(f"\tcolors = {lua(rig['colors'])},")
    lines.append(f"\tglow = {lua(rig.get('glow', {}))},")
    lines.append("\tsegments = {")
    for s in rig["segments"]:
        lines.append(f"\t\t{lua(record(s, SEGMENT_KEYS))},")
    lines.append("\t},")
    lines.append("\tdetails = {")
    for d in rig["details"]:
        lines.append(f"\t\t{lua(record(d, DETAIL_KEYS))},")
    lines.append("\t},")
    lines.append("}")
    lines.append("-- stylua: ignore end")
    lines.append(END)
    return "\n".join(lines)


TEMPLATE = """--!strict
-- {name}'s body plan and animations. The body is copied from the roster design; the
-- animations, walk cycle and break settings below are made by hand.
-- Pose values are degrees (pitch = nose up, yaw = turn left, roll) and studs, added on top of
-- the rest pose. Attacks take their timing from Config/Monsters; other actions set timing here.

{body}

return {{
	displayName = body.displayName,
	hipHeight = body.hipHeight,
	rootSize = body.rootSize,
	colors = body.colors,
	glow = body.glow,
	segments = body.segments,
	details = body.details,
	gait = {{
		stepLength = 6,
		stride = 20,
		knee = 0,
		bob = 0.2,
		tailSway = 0,
		-- Leg joints and when in the step each one swings (0 to 1).
		legs = {{}},
		knees = {{}},
		tail = {{}},
		neck = "Neck",
		jaw = "Jaw",
	}},
	-- Segments that drop off (turn invisible) when their part breaks.
	fallsOff = {{}},
	animations = {{
		flinch = {{
			timing = {{ windup = 0.12, active = 0.1, recovery = 0.6 }},
			windup = {{}},
			strike = {{}},
		}},
		death = {{
			timing = {{ windup = 0.5, active = 1.0, recovery = 0 }},
			hold = true,
			windup = {{}},
			strike = {{}},
		}},
	}},
}}
"""


def main():
    name = sys.argv[1]
    with open(os.path.join(REPO, "tools", "roster", "rigs", f"{name}.rig.json")) as f:
        rig = json.load(f)
    path = os.path.join(REPO, "src", "shared", "Rigs", f"{name}.luau")
    generated = body(rig)
    if os.path.exists(path):
        with open(path) as f:
            text = f.read()
        start, stop = text.index(BEGIN), text.index(END) + len(END)
        text = text[:start] + generated + text[stop:]
    else:
        text = TEMPLATE.format(name=name, body=generated)
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(path, REPO)}")


main()
